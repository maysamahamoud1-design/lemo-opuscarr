# Scene timings from the voice durations: start = prev + max(3, line + 0.45); a 0.7 s near-silence before s09; CTA held 2 s.
import json, os
H = os.path.dirname(os.path.abspath(__file__)) + '/..'
lines = json.load(open(f'{H}/lines.json')); dur = json.load(open(f'{H}/voices/dur.json'))
t = 0.25; S = []
for L in lines:
    if L['id'] == 's09': t += 0.7
    d = dur[L['id']]; S.append({'id': L['id'], 't': round(t, 3), 'v': round(t + .1, 3), 'vd': d, 'text': L['text']})
    t += max(3.0, d + .45)
end = S[-1]['v'] + S[-1]['vd'] + 2.0
for i, s in enumerate(S): s['end'] = S[i + 1]['t'] if i + 1 < len(S) else round(end, 3)
open(f'{H}/timeline.js', 'w').write('// generated by tools/timeline.py\nexport const SC = ' + json.dumps(S, ensure_ascii=False, indent=0) + ';\nexport const DUR = ' + str(round(end, 3)) + ';\n')
print('DUR', round(end, 2)); [print(s['id'], s['t'], s['end']) for s in S]
