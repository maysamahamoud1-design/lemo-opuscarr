// Land polygons (Natural Earth 1:50m via world-atlas, no borders) clipped to the board, in board units (1 unit = 1 degree).
import fs from 'fs'; import { feature } from 'topojson-client';
const topo = JSON.parse(fs.readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);
const B = { lon0: 10, lon1: 82, lat0: -34, lat1: 38 };
function clip(poly) { // Sutherland–Hodgman against the lon/lat box
  const edges = [[p => p[0] >= B.lon0, (a, b) => inter(a, b, 0, B.lon0)], [p => p[0] <= B.lon1, (a, b) => inter(a, b, 0, B.lon1)],
                 [p => p[1] >= B.lat0, (a, b) => inter(a, b, 1, B.lat0)], [p => p[1] <= B.lat1, (a, b) => inter(a, b, 1, B.lat1)]];
  let out = poly;
  for (const [ins, X] of edges) { const inp = out; out = []; for (let i = 0; i < inp.length; i++) { const c = inp[i], p = inp[(i + inp.length - 1) % inp.length]; if (ins(c)) { if (!ins(p)) out.push(X(p, c)); out.push(c); } else if (ins(p)) out.push(X(p, c)); } if (!out.length) break; }
  return out;
}
function inter(a, b, k, v) { const t = (v - a[k]) / (b[k] - a[k]); return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]; }
function simplify(pts, tol) { const o = [pts[0]]; for (const p of pts) { const q = o[o.length - 1]; if (Math.hypot(p[0] - q[0], p[1] - q[1]) >= tol) o.push(p); } return o; }
const polys = [];
for (const f of land.features) for (const poly of (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates)) {
  const c = clip(poly[0].slice(0, -1)); if (c.length < 3) continue;
  const s = simplify(c, .18); if (s.length < 3) continue;
  const ly = s.map(p => p[1]), lx = s.map(p => p[0]); if (Math.max(...ly) - Math.min(...ly) < .3 || Math.max(...lx) - Math.min(...lx) < .3) continue; // slivers left by clipping
  let A = 0; for (let i = 0; i < s.length; i++) { const a = s[i], b = s[(i + 1) % s.length]; A += a[0] * b[1] - b[0] * a[1]; }
  if (Math.abs(A) < .3) continue;
  polys.push(s.map(p => [+p[0].toFixed(2), +p[1].toFixed(2)]));
}
fs.writeFileSync(new URL('../geo.js', import.meta.url), `// generated by tools/geo.mjs from Natural Earth 1:50m land (public domain), lon/lat degrees\nexport const BOX = ${JSON.stringify(B)};\nexport const LAND = ${JSON.stringify(polys)};\n`);
console.log(polys.length, 'polygons', polys.map(p => p.length));
