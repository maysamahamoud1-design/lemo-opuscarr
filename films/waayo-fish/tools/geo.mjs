// Flat map data from Natural Earth (public domain) via world-atlas (ISC) → geo.js
// usage (from this folder): node tools/geo.mjs <path to node_modules>
import fs from 'fs'; import path from 'path';
const NM = process.argv[2];
const { feature, merge } = await import(path.join(NM, 'topojson-client/src/index.js'));
const r2 = v => Math.round(v * 100) / 100, ring = r => r.map(([x, y]) => [r2(x), r2(y)]);
const load = f => JSON.parse(fs.readFileSync(path.join(NM, 'world-atlas', f)));
const crop = (topo, x0, x1, y0, y1) => feature(topo, topo.objects.land).features[0].geometry.coordinates.map(p => p[0])
  .filter(r => r.length >= 4 && !r.every(([x, y]) => x < x0 || x > x1 || y < y0 || y > y1)).map(ring);
const c50 = load('countries-50m.json');
const som = merge(c50, c50.objects.countries.geometries.filter(g => ['Somalia', 'Somaliland'].includes(g.properties.name)));
const SOM = som.coordinates.map(p => ring(p[0])).sort((a, b) => b.length - a.length).slice(0, 1);
// the coast only: from the Djibouti border, round Ras Caseyr, to the Kenya border
const R = SOM[0], near = (q) => R.reduce((b, p, i) => (Math.hypot(p[0] - q[0], p[1] - q[1]) < Math.hypot(R[b][0] - q[0], R[b][1] - q[1]) ? i : b), 0);
const iA = near([43.25, 11.47]), iC = near([51.27, 11.83]), iZ = near([41.56, -1.66]), n = R.length;
const walk = (d) => { const out = []; for (let i = iA; ; i = (i + d + n) % n) { out.push(R[i]); if (i === iZ) break; } return out; };
let COAST = walk(1); if (!COAST.some((p) => p === R[iC])) COAST = walk(-1);
const HORN = crop(load('land-50m.json'), 28, 64, -10, 22);
const LAND = crop(load('land-110m.json'), -180, 180, -60, 85);
fs.writeFileSync('geo.js', '// Natural Earth (public domain) via world-atlas 2.0.2 (ISC). Generated by tools/geo.mjs\nwindow.SOM = ' + JSON.stringify(SOM) + ';\nwindow.COAST = ' + JSON.stringify(COAST) + ';\nwindow.HORN = ' + JSON.stringify(HORN) + ';\nwindow.LAND = ' + JSON.stringify(LAND) + ';\n');
console.log('SOM', R.length, 'COAST', COAST.length, COAST[0], COAST[COAST.length - 1], 'HORN', HORN.length, 'LAND', LAND.length);
