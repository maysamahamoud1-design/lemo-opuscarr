# Scene timings from the voice: the voice starts at 0.1 s; each next line starts 0.3 s after the previous one ends; the last card holds 1.6 s.
import json, os
H = os.path.dirname(os.path.abspath(__file__)) + '/..'
lines = json.load(open(f'{H}/lines.json')); dur = json.load(open(f'{H}/voices/dur.json'))
v = 0.1; S = []
for L in lines:
    d = dur[L['id']]; S.append({'id': L['id'], 't': round(max(0, v - 0.1), 3), 'v': round(v, 3), 'vd': d, 'text': L['text']}); v += d + 0.25
end = S[-1]['v'] + S[-1]['vd'] + 1.6
for i, s in enumerate(S): s['end'] = S[i + 1]['t'] if i + 1 < len(S) else round(end, 3)
open(f'{H}/timeline.js', 'w').write('// generated by tools/timeline.py\nwindow.SC = ' + json.dumps(S, ensure_ascii=False, indent=0) + ';\nwindow.DUR = ' + str(round(end, 3)) + ';\n')
print('DUR', round(end, 2)); [print(s['id'], s['t'], s['end']) for s in S]
