// Flat map data from Natural Earth (via the world-atlas package, ISC; Natural Earth is public domain) → geo.js
// usage (from this folder): node tools/geo.mjs <path to node_modules>
import fs from 'fs'; import path from 'path';
const NM = process.argv[2];
const { feature, merge } = await import(path.join(NM, 'topojson-client/src/index.js'));
const r2 = v => Math.round(v * 100) / 100;
const ring = r => r.map(([x, y]) => [r2(x), r2(y)]);
// Somalia as one shape (Natural Earth splits it in two)
const c50 = JSON.parse(fs.readFileSync(path.join(NM, 'world-atlas/countries-50m.json')));
const som = merge(c50, c50.objects.countries.geometries.filter(g => ['Somalia', 'Somaliland'].includes(g.properties.name)));
const SOM = som.coordinates.map(p => ring(p[0])).sort((a, b) => b.length - a.length).slice(0, 1);
// land for the world card, cropped to lon -140..75, lat -8..78
const l110 = JSON.parse(fs.readFileSync(path.join(NM, 'world-atlas/land-110m.json')));
const land = feature(l110, l110.objects.land);
const LAND = [];
for (const poly of land.features[0].geometry.coordinates) {
  const r = poly[0]; if (r.length < 4) continue;
  if (r.every(([x, y]) => x < -140 || x > 75 || y < -8 || y > 80)) continue;
  LAND.push(ring(r));
}
fs.writeFileSync('geo.js', '// Natural Earth (public domain) via world-atlas 2.0.2 (ISC). Generated by tools/geo.mjs\nwindow.SOM = ' + JSON.stringify(SOM) + ';\nwindow.LAND = ' + JSON.stringify(LAND) + ';\n');
console.log('SOM pts', SOM[0].length, 'LAND polys', LAND.length);
